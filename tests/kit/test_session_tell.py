# --- brief #368 answer 2: after prints the unread Tell lines first --------------------------------


def configure(proj, value: str) -> None:
    proj.write("agk.toml", f'default_branch = "main"\npr_mode = "flow"\n[flow]\nassign = "{value}"\n')


def after(proj, stub):
    return session(proj, stub, "after", "--session", "s-me")


def test_after_prints_the_inbox_once_and_then_nothing(proj, stub):
    """REQ-040: brief #368 answers 2 and 4."""
    configure(proj, "conductor")
    stub.serve(CONDUCTOR, [CONDUCTOR_ISSUE])
    stub.serve(
        COMMENTS,
        [
            told(1, "Tell: s-me before the request"),
            comment(2, "builder", "Request: s-me finished #5"),
            told(3, "Tell: s-me #52 merged, rebase"),
            told(4, "Tell: s-other not mine"),
        ],
    )
    first = after(proj, stub)
    assert first.returncode == 0, first.stdout
    assert first.stdout.splitlines() == ["Tell: s-me #52 merged, rebase", "ask the conductor on #204"]
    second = after(proj, stub)
    assert second.stdout.splitlines() == ["ask the conductor on #204"]
    assert inbox(proj, stub).stdout.splitlines() == ["no message"]  # the same mark
    assert posts(stub) == []


def test_after_reads_the_mark_the_inbox_wrote(proj, stub):
    """REQ-040: brief #368 answer 2 (with the same mark)."""
    configure(proj, "conductor")
    stub.serve(CONDUCTOR, [CONDUCTOR_ISSUE])
    stub.serve(COMMENTS, [told(3, "Tell: s-me read already")])
    assert inbox(proj, stub).stdout.splitlines() == ["Tell: s-me read already"]
    assert after(proj, stub).stdout.splitlines() == ["ask the conductor on #204"]


def test_after_says_so_when_the_inbox_cannot_be_read_and_goes_on(proj, stub):
    """REQ-040: brief #368 answer 2 (an unread inbox is never shown as an empty one)."""
    configure(proj, "conductor")
    stub.serve(CONDUCTOR, [CONDUCTOR_ISSUE])
    stub.serve(COMMENTS, "FAIL")
    out = after(proj, stub)
    assert out.stdout.splitlines() == [
        "tell: the comments of #204 cannot be read",
        "ask the conductor on #204",
    ]
