def kit_only_folders(manifest: dict) -> tuple[str, ...]:
    """Brief #1752 (ADR-0732): the `snapshot` folders under which no template, rendered or rule 2
    kept path lies, and the `kit_tests` folder, which the snapshot no longer ships (brief #1886,
    ADR-0780) but a product still never holds. Raises ValueError without a `snapshot` list."""
    snapshot = manifest.get("snapshot")
    if not isinstance(snapshot, list):
        raise ValueError("snapshot")
    held = [
        *(manifest.get("templates") or {}),
        *(manifest.get("rendered") or []),
        *KEEPS,
        *KEEPS_UNDER,
    ]
    folders = [str(p) for p in snapshot if str(p).endswith("/")]
    tests = str(manifest.get("kit_tests") or "").strip("/")
    folders += [f"{tests}/"] if tests and f"{tests}/" not in folders else []
    return tuple(f for f in folders if not any(str(h).startswith(f) for h in held))


@lru_cache(maxsize=4)
def kit_paths(project: str) -> tuple[frozenset[str], str, tuple[str, ...]] | None:
    """In a clean project, the plugin's manifest paths a product never holds, its kit tests' folder
    and its kit-only folders; None in an installed project. Raises ValueError when the manifest
    cannot be read or has no `snapshot` list."""
    try:
        import tomllib

        kit = tomllib.loads((Path(project) / "agk.toml").read_text(encoding="utf-8")).get("kit")
    except (OSError, ValueError, ImportError):
        return None
    if not isinstance(kit, dict) or kit.get("layout") != "plugin":
        return None
    path = Path(__file__).resolve().parents[2] / "kit" / "manifest.json"
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
        listed = [*manifest.get("verbatim", []), *manifest.get("experimental", [])]
        tests = str(manifest.get("kit_tests") or "").strip("/")
        folders = kit_only_folders(manifest)
    except (OSError, ValueError, AttributeError, TypeError):
        raise ValueError("manifest") from None
    keep = [p for p in listed if p not in KEEPS and not p.startswith(KEEPS_UNDER)]
    return frozenset(keep), tests, folders


def kit_state(project: Path) -> str | None:
    """`clean` when the manifest was read, `unknown` when it cannot be, None in an installed one."""
    try:
        return "clean" if kit_paths(str(project)) is not None else None
    except ValueError:
        return "unknown"


CANNOT = f"steward guard: {KIT_RULE} denies a write it cannot check (path class: kit/manifest.json)"


def project_rel(target: str, cwd: Path, project: Path) -> str:
    """`target` relative to the project, a back slash read as a forward slash (brief #1748)."""
    path = Path(target.replace("\\", "/"))
    whole = os.path.normpath(path if path.is_absolute() else cwd / path)
    return os.path.relpath(whole, os.path.normpath(project)).replace("\\", "/")


def kit_denial(where: str) -> str:
    return (
        f"steward guard: {KIT_RULE} denies kit code written into the product (path class: {where})"
    )


def kit_write(target: str, cwd: Path, project: Path) -> str | None:
    """The denial of a write of `target` when it is a kit manifest path, or lies in a kit-only
    folder, in a clean product."""
    try:
        found = kit_paths(str(project))
    except ValueError:
        return CANNOT
    if found is None or not target:
        return None
    rel = project_rel(target, cwd, project)
    paths, tests, folders = found
    if inside := [f for f in folders if (rel + "/").startswith(f)]:
        where = inside[0]
    elif rel in paths:
        where = rel.rsplit("/", 1)[0] + "/" if "/" in rel else rel
    elif tests and rel.startswith(tests + "/"):
        where = tests + "/"
    else:
        return None
    return kit_denial(where)


COPIERS = frozenset({"cp", "mv", "install", "ln", "rsync", "scp", "ditto"})
UNPACK_DIR = {
    "tar": ("-C", "--directory"),
    "unzip": ("-d",),
    "cpio": ("-D", "--directory"),
    "7z": ("-o",),
}


def option_value(words: list[str], flags: tuple[str, ...]) -> str | None:
    """The value of the last of `flags` given (`-C dir`, `--directory=dir`, `-odir`)."""
    value = None
    for i, word in enumerate(words):
        for flag in flags:
            if word == flag and i + 1 < len(words):
                value = words[i + 1]
            elif flag.startswith("--") and word.startswith(flag + "="):
                value = word[len(flag) + 1 :]
            elif flag in ("-o", "-t") and word.startswith(flag) and len(word) > 2:
                value = word[2:]
    return value


def operands(words: list[str]) -> list[str]:
    """The words after the command that are neither options nor redirections (nor their files)."""
    out, skip = [], False
    for word in words[1:]:
        if skip:
            skip = False
        elif REDIRECT.match(word):
            skip = not REDIRECT.sub("", word)
        elif word in ("-t", "-S", "--suffix"):
            skip = True
        elif not word.startswith("-"):
            out.append(word)
    return out


def short_flag(words: list[str], letters: str) -> bool:
    return any(w[:1] == "-" and w[1:2] != "-" and set(w[1:]) & set(letters) for w in words[1:])


def copy_target(words: list[str], cwd: Path) -> tuple[str, bool, list[str]] | None:
    """Brief #1752 answer 3: a copy's or an unpack's destination, whether it is recursive and the
    sources of a copy; None for another command."""
    name, first = os.path.basename(words[0]), (words[1:] or [""])[0]
    if name in COPIERS:
        rest, target = operands(words), option_value(words, ("-t", "--target-directory"))
        if target is None and len(rest) < 2:
            return None
        target, rest = (target, rest) if target is not None else (rest[-1], rest[:-1])
        long = {"--recursive", "--archive"} & set(words)
        return target, name in ("rsync", "ditto") or short_flag(words, "rRa") or bool(long), rest
    unpack = {
        "tar": short_flag(words, "x")
        or "--extract" in words
        or (first[:1] != "-" and "x" in first),
        "unzip": True,
        "cpio": short_flag(words, "i") or "--extract" in words,
        "7z": first in ("x", "e"),
    }.get(name, False)
    return (option_value(words, UNPACK_DIR[name]) or str(cwd), True, []) if unpack else None


def copy_problem(words: list[str], cwd: Path, project: Path, state: str) -> str | None:
    """A recursive copy or unpack whose destination is, lies under or holds a kit-only folder;
    a plain copy judged by each path it makes (ADR-0732 decision 3)."""
    if (found := copy_target(words, cwd)) is None:
        return None
    target, recursive, sources = found
    rel = project_rel(target, cwd, project)
    above = rel == "." or set(rel.split("/")) == {".."}  # the project's root or a folder holding it
    if rel.startswith("..") and not above:
        return None
    if state == "unknown":
        return CANNOT if recursive else None
    if recursive:
        prefix = "" if above else rel + "/"
        found = kit_paths(str(project))
        held = [f for f in (found[2] if found else ()) if f.startswith(prefix)]
        return kit_write(target, cwd, project) or (kit_denial(", ".join(held)) if held else None)
    folder = target.endswith(("/", "\\")) or len(sources) > 1 or (cwd / target).is_dir()
    made = [f"{target}/{os.path.basename(x.rstrip('/'))}" for x in sources] if folder else []
    return next((p for m in made if (p := kit_write(m, cwd, project))), None)


def git_gh_targets(words: list[str]) -> list[str]:
    """Q-A-1's conservative reading: the paths `git checkout <ref> -- <paths>`, `git restore
    --source` and `gh release download -D/-O` write; git and gh stay readers otherwise."""
    if words[0] == "git" and "checkout" in words and "--" in words:
        return words[words.index("--") + 1 :]
    if words[0] == "git" and "restore" in words and option_value(words, ("--source",)):
        source = option_value(words, ("--source",))
        return [w for w in operands(words) if w not in ("restore", source)]
    if words[0] == "gh" and words[1:3] == ["release", "download"]:
        return [v for f in (("-D", "--dir"), ("-O", "--output")) if (v := option_value(words, f))]
    return []


def read_value(value: str, cwd: Path) -> str | None:
    """A `-F key=@file` value's text; None when it cannot be read (stdin, a missing file)."""
    if not value.startswith("@"):
        return value
    if value == "@-":
        return None
    path = Path(value[1:])
    try:
        return (path if path.is_absolute() else cwd / path).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def approval_problem(text: str, inline: bool, project: Path | None) -> str | None:
    """Brief #1691 (amendment 194 item 6): an `Approve:` or `Confirmed:` passes only from a file,
    closing with one `Owner said` and one `Asked` line (an `Approve:`: the last three lines with
    `Who: ProductOwner`; a `Confirmed:`: the two before `Shown:`, `Who: ProductOwner` last), in
    solo mode with one person listed, and never in a steward the conductor started."""
    lines = [x.strip() for x in FOOTER.sub("", text.replace("\r\n", "\n")).splitlines()]
    lines = [x for x in lines if x]
    owner = [i for i, x in enumerate(lines) if OWNER_SAID.match(x)]
    asked = [i for i, x in enumerate(lines) if ASKED.fullmatch(x)]
    end = lines.index("Shown:") if lines[0].startswith("Confirmed:") and "Shown:" in lines else 0
    end = end or len(lines) - 1
    if inline or lines[-1] != OWNER_WHO or owner != [end - 2] or asked != [end - 1]:
        return reason("a reserved first line", "comment first line")
    if os.environ.get("AGK_STEWARD_START") == "conductor":
        return f"steward guard: {RULE} denies an approval (setting: AGK_STEWARD_START)"
    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts" / "agk"))
    try:
        from reviewers import solo_person

        person = solo_person(project or Path("."))
    except Exception:  # noqa: BLE001 - an unreadable mode fails closed
        person = None
    if not person:
        return (
            f"steward guard: {RULE} denies an approval outside solo mode with one person listed "
            "(setting: review_mode)"
        )
    return None


def settled_problem(text: str, project: Path | None) -> str | None:
    """Brief #1957 (ADR-0813, amendment 251): a settled line passes only in its full form, with
    `Who: AGK steward` and the `Text:` digest of its amendment as the checkout reads it, for an
    amendment that is settleable, while `[steward] settle_amendments` is on."""
    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts" / "agk"))
    try:
        from check_amendments import SETTLED, amendment_path, digests, settle_on, settled_key

        root = project or Path(".")
        found = SETTLED.fullmatch(text.splitlines()[0].strip())
        key = f"amendment {int(found.group(1))}" if found else ""
        on = settle_on(root)
        path = root / amendment_path(key) if key else None
        texts = {key: path.read_text(encoding="utf-8")} if path and path.is_file() else {}
        settles = digests(texts, root) if on else {}
        settled = settled_key(text.splitlines()[0].strip(), text, settles)
    except Exception:  # noqa: BLE001 - an unreadable setting or amendment fails closed
        on, settled = False, None
    if not on:
        return f"steward guard: {RULE} denies a settled line (setting: steward.settle_amendments)"
    if settled is None:  # fix list item 2: the form, the marker and the amendment as it reads
        return reason("a settled line not in its form or for its amendment", "docs/runs/")
    return None


def body_problem(text: str | None, inline: bool = False, project: Path | None = None) -> str | None:
    """A typed body may hold no substitution (`$(` or a backtick): the shell would run it."""
    if text is None or (inline and ("$(" in text or "`" in text)):
        return reason("a body it cannot read", "comment body")
    text = ZERO_WIDTH.sub("", text).lstrip()  # brief #1732: a zero-width start reads as the line
    lines = text.splitlines() or [""]
    if lines[0].startswith(APPROVALS):
        return approval_problem(text, inline, project)
    if lines[0].startswith(RESERVED):
        return reason("a reserved first line", "comment first line")
    if SETTLED_START.match(lines[0]):
        return settled_problem(text, project)
    if lines[0].startswith("Maintainer answer:"):
        if len(lines) < 2 or not OWNER_SAID.match(lines[1]):
            return reason("an owner answer without the owner's quote", "comment second line")
    return None


def filing_problem(text: str | None, project: Path) -> str | None:
    if text is None:
        return reason("a body it cannot read", "issue body")
    found = PRIORITY.search(text)
    if found is None or OWNER_LINE.search(text):
        return None
    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts" / "agk"))
    try:
        from config import steward_settings

        limit = steward_settings(project)["auto_file"]
    except Exception as exc:  # noqa: BLE001 - a refused or unreadable table fails closed
        setting = re.search(r"setting: ([\w.]+)", str(exc))
        name = setting[1] if setting else "steward"
        return f"steward guard: {RULE} denies a filing (setting: {name})"
    if limit is False or int(found[1]) > limit:
        return (
            f"steward guard: {RULE} denies a filing above the priority (setting: steward.auto_file)"
        )
    return None


def body_edit_problem(project: Path) -> str | None:
    """Brief #1715 (ADR-0714): an issue body edit passes only with `[steward] fix_briefs = true`."""
    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts" / "agk"))
    try:
        from config import steward_settings

        allowed = steward_settings(project)["fix_briefs"] is True
    except Exception:  # noqa: BLE001 - a refused or unreadable table fails closed
        allowed = False
    if allowed:
        return None
    return f"steward guard: {RULE} denies a brief body edit (setting: steward.fix_briefs)"


def outbound_problem(target: str | None, texts: list[str | None], project: Path) -> str | None:
    """Rule 11: a post to the kit repository from another project passes the outbound guard."""
    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts" / "agk"))
    try:
        import steward_outbound as outbound
    except ImportError:
        return reason("a post to the kit repository it cannot check", "outbound data guard")
    repo = (target or "").lower().removesuffix(".git")
    if not repo:
        return None  # the project's own repository
    kit, found = outbound.kit_repo(project), outbound.remotes(project)
    if kit is None:  # no kit named: any other repository may be the kit's, fail closed
        if found is not None and repo in {r for _, r in found}:
            return None
    elif repo != kit or outbound.is_kit(found, kit):
        return None  # another repository, or the kit's own steward: nothing leaves a project
    if any(t is None for t in texts):
        return reason("a post to the kit repository it cannot check", "comment body")
    lines = outbound.check("\n".join(t for t in texts if t), project, found, kit)
    if not lines:
        return None
    what = "; ".join(line.split(" refuses ", 1)[1].split("; rewrite", 1)[0] for line in lines)
    return f"steward guard: {RULE} denies a post to the kit repository holding {what}"


def labels_problem(values: list[str], allowed: frozenset[str]) -> str | None:
    names = [n.strip() for v in values for n in v.split(",")]
    return None if all(n in allowed for n in names) else reason("a label write", "label")


def option_values(words: list[str], flags: frozenset[str]) -> list[str]:
    out = []
    for i, word in enumerate(words):
        for flag in flags:
            if word == flag and i + 1 < len(words):
                out.append(words[i + 1])
            elif word.startswith(flag + "=") and flag.startswith("--"):
                out.append(word.split("=", 1)[1])
    return out


def gh_problem(words: list[str], cwd: Path, project: Path) -> str | None:
    sub = words[1] if len(words) > 1 else ""
    verb = words[2] if len(words) > 2 else ""
    if sub == "api":
        return api_problem(words[2:], cwd, project)
    if sub == "pr" and verb == "merge":
        return reason("a merge or auto-merge", "pull request")
    if sub == "release" or (sub == "workflow" and verb in ("run", "enable", "disable")):
        return reason("a tag or a workflow change", "`.github/`")
    if sub in ("secret", "ruleset") and verb not in ("list", "view", "check"):
        return reason("a secret or ruleset change", sub)
    if sub == "label" and verb not in ("list", "view"):
        return reason("a label write", "label")
    added = option_values(words, frozenset({"--add-label", "--remove-label", "--label", "-l"}))
    if sub == "pr" and verb == "edit":
        return labels_problem(added, frozenset({"agk:parked"}))
    if sub == "issue" and verb in ("create", "edit"):
        allowed = FILED if verb == "create" else frozenset({"agk-steward"})
        if problem := labels_problem(added, allowed):
            return problem
    texts = [(v, True) for v in option_values(words, BODY_FLAGS)]
    files = option_values(words, frozenset({"--body-file", "-F"}))
    texts += [(None if v == "-" else read_value("@" + v, cwd), False) for v in files]
    if sub == "issue" and verb == "edit" and texts and (problem := body_edit_problem(project)):
        return problem
    for text, inline in texts:
        if sub == "issue" and verb == "create":
            problem = filing_problem(text, project) or body_problem(text, inline, project)
        else:
            problem = (
                body_problem(text, inline, project)
                if verb in ("comment", "review", "edit")
                else None
            )
        if problem:
            return problem
    target = (option_values(words, frozenset({"-R", "--repo"})) or [None])[0]
    titles = option_values(words, frozenset({"-t", "--title"})) if sub == "issue" else []
    return outbound_problem(target, [*titles, *(t for t, _ in texts)], project)


def api_problem(words: list[str], cwd: Path, project: Path) -> str | None:
    endpoint, method, fields, skip, inline = "", None, {}, False, set()
    for i, word in enumerate(words):
        if skip:
            skip = False
            continue
        if word in ("-X", "--method") and i + 1 < len(words):
            method, skip = words[i + 1].upper(), True
        elif word in VALUE_FLAGS:
            skip = True
        elif word.startswith("--method="):
            method = word.split("=", 1)[1].upper()
        elif word in FIELD_FLAGS and i + 1 < len(words):
            key, _, value = words[i + 1].partition("=")
            typed = word in ("-f", "--raw-field") or not value.startswith("@")
            fields.setdefault(key, []).append(value if typed else read_value(value, cwd))
            if typed:
                inline.add(key)
            skip = True
        elif word == "--input":
            return reason("a body it cannot read", "request input")
        elif not word.startswith("-") and not endpoint:
            endpoint = word
    if endpoint.strip("/") == "graphql":
        return "steward guard: CLAUDE.md item 10 denies a GraphQL call (path class: gh api graphql)"
    if (method or ("POST" if fields else "GET")) == "GET":
        return None
    path = endpoint.split("?", 1)[0]
    for pattern, what in API_DENIED:
        if pattern.search(path):
            return reason(what, "gh api endpoint")
    if kit := re.match(r"^/?repos/([^/{}]+/[^/{}]+)/", path):
        posted = [v for k in ("title", "body") for v in fields.get(k, [])]
        if problem := outbound_problem(kit[1], posted, project):
            return problem
    if re.search(r"/issues/\d+/labels", path):
        named = [v or "?" for k, vs in fields.items() if k.startswith("labels") for v in vs]
        if method == "DELETE" and not fields:
            named = [path.rsplit("/", 1)[1]]
        return labels_problem(named or ["?"], LABELS)
    named = [v or "?" for k, vs in fields.items() if k.startswith("labels") for v in vs]
    if re.search(r"/issues$", path):
        if problem := labels_problem(named, FILED):
            return problem
        text = (fields.get("body") or [""])[0]
        return filing_problem(text, project) or body_problem(text, "body" in inline, project)
    if named:
        return reason("a label write", "label")
    if re.search(r"/issues/\d+$", path) and "body" in fields:
        if problem := body_edit_problem(project):
            return problem
    for text in fields.get("body", []):
        if problem := body_problem(text, "body" in inline, project):
            return problem
    return None


# Brief #1834 (ADR-0763): a push, a setting, an alias or `update-ref` is read as git reads it.
GIT_VALUED = frozenset({"-C", "-c", "--git-dir", "--work-tree", "--namespace", "--config-env"})
GIT_WHERE = ("-C", "--git-dir", "--work-tree")  # passed on to the guard's own git reads
PUSH_VALUED = frozenset({"-o", "--push-option", "--receive-pack", "--exec", "--repo"})
RISKY_KEY = re.compile(r"^(?:push\.followtags|remote\..+\.(?:push|mirror|tagopt)|alias\..+)$", re.I)
CONFIG_READS = frozenset(
    {"--get", "--get-all", "--get-regexp", "--get-urlmatch", "-l", "--list", "get", "list"}
)
CONFIG_WRITES = frozenset({"--add", "--replace-all", "--unset", "--unset-all", "set", "unset"})
TRUE = frozenset({"true", "yes", "on", "1"})
GIT_BUILTINS = frozenset(
    "add am apply archive bisect blame branch bundle cat-file check-ignore checkout cherry "
    "cherry-pick clean clone commit config describe diff fetch for-each-ref format-patch fsck "
    "gc grep hash-object help init log ls-files ls-remote ls-tree maintenance merge merge-base "
    "mktag mv notes pull push range-diff rebase reflog remote replace reset restore rev-list "
    "rev-parse revert rm shortlog show show-ref sparse-checkout stash status submodule switch "
    "symbolic-ref tag update-index update-ref var version worktree write-tree".split()
)
GIT_SECONDS = 1.0  # each read; three fit the hook's 4-second budget


def git_read(where: list[str], cwd: Path, *args: str) -> tuple[int, str] | None:
    """One local read (`for-each-ref`, `config`); None when git cannot be run or passes its time."""
    import subprocess  # nosec B404 - fixed argument lists only, no shell

    env = {**os.environ, "LC_ALL": "C", "GIT_TERMINAL_PROMPT": "0"}
    try:
        proc = subprocess.run(  # nosec B603 B607 - fixed argument list, no shell, no network
            ["git", *where, *args],
            cwd=cwd,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            env=env,
            timeout=GIT_SECONDS,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return proc.returncode, proc.stdout + ("\0" + proc.stderr if proc.returncode else "")


def git_config(where: list[str], cwd: Path, pattern: str) -> list[tuple[str, str]] | None:
    """The `key value` pairs of `git config --get-regexp`, keys lower-cased; None if unreadable."""
    found = git_read(where, cwd, "config", "--get-regexp", pattern)
    if found is None or found[0] not in (0, 1):
        return None
    lines = found[1].split("\0", 1)[0].splitlines() if found[0] == 0 else []
    return [(k.lower(), v) for k, _, v in (line.partition(" ") for line in lines)]


def local_tags(where: list[str], cwd: Path) -> set[str] | None:
    """The short names of the local tags; empty outside a repository, where git refuses a push."""
    found = git_read(where, cwd, "for-each-ref", "--format=%(refname)", "refs/tags/")
    if found is None:
        return None
    if found[0] != 0:
        return set() if "not a git repository" in found[1] else None
    return {line.removeprefix("refs/tags/") for line in found[1].splitlines() if line}


def names_tag(ref: str, tags: set[str]) -> bool:
    """A refspec side that is or as a pattern meets `refs/tags/`, or a local tag's short name."""
    if "*" in ref:
        prefix = ref.split("*", 1)[0]
        return "refs/tags/".startswith(prefix) or prefix.startswith("refs/tags/")
    bare = ref.split("^", 1)[0].split("~", 1)[0]
    return bare.startswith(("refs/tags/", "tags/")) or bare in tags


def config_problem(args: list[str]) -> str | None:
    """A `git config` that writes a push setting or an alias (brief #1834)."""
    if "-e" in args or "--edit" in args or "edit" in args[:1]:
        return reason("a push setting or an alias", "git config")
    if "--rename-section" in args or "rename-section" in args[:1]:
        sections = [a for a in args if not a.startswith("-")]
        if any(a.lower() in ("alias", "push") or a.lower().startswith("remote.") for a in sections):
            return reason("a push setting or an alias", "git config")
        return None
    at = next(
        (k for k, a in enumerate(args) if not a.startswith("-") and a not in ("set", "unset")), None
    )
    if at is None or not RISKY_KEY.match(args[at]) or any(a in CONFIG_READS for a in args):
        return None
    if at + 1 < len(args) or any(
        a in CONFIG_WRITES for a in args
    ):  # a value after the key, or a write
        return reason("a push setting or an alias", "git config")
    return None


def push_problem(args: list[str], where: list[str], cwd: Path) -> str | None:
    """Rule 11 (brief #1834): a refspec, a `tag <name>` or a setting that sends a tag denies."""
    words, i, repo_flag = [], 0, False
    while i < len(args):
        word = args[i]
        if word in PUSH_VALUED:
            repo_flag |= word == "--repo"
            i += 2
            continue
        repo_flag |= word.startswith("--repo=")
        if not word.startswith("-"):
            words.append(word)
        i += 1
    remote = words[0] if words and not repo_flag else ""
    refs = words if repo_flag else words[1:]
    tags = local_tags(where, cwd)
    found = git_config(where, cwd, r"^(push\.followtags|remote\..*\.(push|mirror))$")
    if tags is None or found is None:
        return f"steward guard: {RULE} cannot judge a push (path class: git push)"
    deny = reason("a tag", "git push")
    j = 0
    while j < len(refs):
        if refs[j] == "tag" and j + 1 < len(refs):
            return deny
        src, colon, dst = refs[j].removeprefix("+").rpartition(":")
        src, dst = (src, dst) if colon else (dst, dst)
        if (colon and not src) or names_tag(src, tags) or names_tag(dst, tags):
            return deny
        j += 1
    for key, value in found:
        if "push.followtags" == key and value.lower() in TRUE:
            return f"steward guard: {RULE} denies a tag (setting: push.followTags)"
        if remote and key == f"remote.{remote.lower()}.mirror" and value.lower() in TRUE:
            return f"steward guard: {RULE} denies a tag (setting: remote.<name>.mirror)"
        if remote and key == f"remote.{remote.lower()}.push":
            src, _, dst = value.removeprefix("+").rpartition(":")
            if names_tag(src or dst, tags) or names_tag(dst, tags):
                return f"steward guard: {RULE} denies a tag (setting: remote.<name>.push)"
    return None


def git_problem(
    words: list[str], project: Path, cwd: Path | None = None, alias: bool = True
) -> str | None:
    cwd = cwd or project
    i, where, given = 1, [], []
    while i < len(words) and words[i].startswith("-"):
        flag, _, inline = words[i].partition("=")
        value = inline if inline else (words[i + 1] if i + 1 < len(words) else "")
        if flag in ("-c", "--config-env"):
            given.append(value.partition("=")[0])
        if flag in GIT_WHERE:
            where += [flag, value]
        i += 1 if inline or flag not in GIT_VALUED else 2
    if any(RISKY_KEY.match(key) for key in given):
        return reason("a push setting or an alias", "git config")
    sub, args = (words[i], words[i + 1 :]) if i < len(words) else ("", [])
    if any(".github/" in a for a in args) and sub not in READ_GIT:
        return reason("a change to a workflow file", "`.github/`")
    if sub and sub not in GIT_BUILTINS and not sub.startswith("-"):
        found = git_config(where, cwd, r"^alias\.")
        expansion = dict(found or []).get(f"alias.{sub.lower()}")
        if found is None or (expansion is not None and (not alias or expansion.startswith("!"))):
            return reason("an alias it cannot judge", "git alias")
        if expansion is not None:
            try:
                expanded = shlex.split(expansion)
            except ValueError:
                return reason("an alias it cannot judge", "git alias")
            return git_problem([*words[:i], *expanded, *args], project, cwd, alias=False)
    if sub == "merge":
        return reason("a merge", "git merge")
    if sub == "tag" and any(a not in ("-l", "--list") and not a.startswith("--sort") for a in args):
        return reason("a tag", "git tag")
    if sub == "config":
        return config_problem(args)
    if sub == "update-ref":
        names = [a for a in args if not a.startswith("-")]
        tags = local_tags(where, cwd) if names else set()
        if "--stdin" in args or tags is None or any(names_tag(a, tags) for a in names):
            return reason("a tag", "git update-ref")
        return None
    if sub == "fetch":
        refs = [a for a in args if not a.startswith("-")][1:]
        if (
            "--tags" in args
            or "-t" in args
            or any(names_tag(r.rpartition(":")[2], set()) for r in refs if ":" in r)
        ):
            return reason("a tag", "git fetch")
        return None
    if sub != "push":
        return None
    if any(FORCE.match(a) or a.startswith("+") for a in args):
        return reason("a force push, a tag or a delete", "git push")
    refs = [a for a in args if not a.startswith("-")][1:]
    branch = default_branch(project)
    if not refs:
        return reason("a push with no branch named", "git push")
    for ref in refs:
        target = ref.rsplit(":", 1)[-1].removeprefix("refs/heads/")
        if target in (branch, "HEAD") or target.startswith("refs/tags/"):
            return reason("a push to the default branch or a tag", "default branch")
    return push_problem(args, where, cwd)


def segments(command: str) -> list[list[str]] | None:
    try:
        lexer = shlex.shlex(command, posix=True, punctuation_chars=";&|\n")
        lexer.whitespace = " \t\r"
        lexer.whitespace_split = True
        words = list(lexer)
    except ValueError:
        return None
    out: list[list[str]] = [[]]
    for word in words:
        if word in OPERATORS or set(word) <= set(";&|\n"):
            out.append([])
        else:
            out[-1].append(word)
    return [s for s in out if s]


def decide(payload: dict) -> str | None:
    tool = payload.get("tool_name")
    data = payload.get("tool_input") or {}
    project = Path(os.environ.get("CLAUDE_PROJECT_DIR") or payload.get("cwd") or ".")
    cwd = Path(payload.get("cwd") or project)
    if str(tool or "").casefold() == "powershell":  # brief #1763: one reader per tool
        return POWERSHELL_RULE
    if tool in WRITE_TOOLS:
        target = Path(str(data.get("file_path") or data.get("notebook_path") or ""))
        rel = os.path.relpath(target if target.is_absolute() else cwd / target, project)
        if rel.replace("\\", "/").startswith(".github/"):
            return reason("a change to a workflow file", "`.github/`")
        return kit_write(str(target), cwd, project)
    if tool != "Bash":
        return None
    return bash_problem(str(data.get("command") or ""), cwd, project, 0)


def bash_problem(command: str, cwd: Path, project: Path, depth: int) -> str | None:
    found = segments(command)
    if found is None or depth > 3:
        return reason("a command it cannot read", "Bash")
    for words in found:
        if problem := command_problem(words, cwd, project, depth):
            return problem
    return None


def unwrap(words: list[str]) -> list[str] | None:
    """The command a wrapper runs (`env`, `timeout 60`, `sudo -u x`); None for another word."""
    name = os.path.basename(words[0])
    if name not in WRAPPERS:
        return None
    rest, valued = words[1:], WRAPPERS[name]
    while rest and (rest[0].startswith("-") or (name == "env" and ASSIGN.match(rest[0]))):
        rest = rest[2:] if rest[0] in valued else rest[1:]
    if name == "timeout" and rest:
        rest = rest[1:]  # the duration
    return rest


def command_problem(words: list[str], cwd: Path, project: Path, depth: int) -> str | None:
    if any("merge_cleared" in w for w in words):
        return reason("a merge", "`scripts/agk/merge_cleared.py`")
    while words and ASSIGN.match(words[0]):
        words = words[1:]  # an environment assignment before the command
    if not words:
        return None
    if (inner := unwrap(words)) is not None:
        return command_problem(inner, cwd, project, depth + 1) if depth < 8 else None
    name = os.path.basename(words[0])
    state = kit_state(project)
    if state == "clean":
        named = redirect_targets(words) + git_gh_targets(words)
        if name not in READERS:
            named += [REDIRECT.sub("", word) for word in words[1:]]
        for word in named:
            if word and (problem := kit_write(word, cwd, project)):
                return problem
    if state and (problem := copy_problem(words, cwd, project, state)):
        return problem
    if name == "find":
        found = [i for i, w in enumerate(words) if w in ("-exec", "-execdir", "-ok", "-okdir")]
        return next(
            (p for i in found if (p := command_problem(words[i + 1 :], cwd, project, depth + 1))),
            None,
        )
    if INTERPRETER.match(name):
        code = [words[i + 1] for i, w in enumerate(words[:-1]) if w in ("-c", "-e", "-E", "--eval")]
        if any(RUNS.search(c) for c in code):
            return reason("inline code that runs gh or git", "interpreter inline code")
        return None
    if any(w.startswith(".github/") or "/.github/" in w for w in words) and name not in (
        "cat",
        "ls",
        "head",
        "grep",
        "git",
        "gh",
        *SHELLS,
    ):
        return reason("a change to a workflow file", "`.github/`")
    if name in SHELLS:
        inner = words[words.index("-c") + 1] if "-c" in words[:-1] else " ".join(words[1:])
        return bash_problem(inner, cwd, project, depth + 1)
    if name in ("git", "git.exe"):
        return git_problem(words, project, cwd)
    if name == "gh":
        return gh_problem(words, cwd, project)
    return None


def keep_refusal(payload: object, found: str) -> bool:
    """Brief #1410 (ADR-0593): one redacted line per denial in `<git common dir>/agk/refusals.log`,
    its reason code the path class the denial names; a failure changes nothing."""
    try:
        match = re.search(r"\(path class: ([^()]+)\)$", found)
        sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts" / "agk"))
        import guard_logs  # noqa: PLC0415 - the kit's own folder, only when something is denied

        code = match.group(1) if match else "other"
        return guard_logs.record_refusal(payload, "steward guard", code, "steward")
    except Exception:  # noqa: BLE001 - keeping the line never changes the decision
        return False


def main() -> int:
    try:
        payload = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        payload = None
    found = (
        decide(payload) if isinstance(payload, dict) else reason("an unreadable call", "hook input")
    )
    if found:
        keep_refusal(payload, found)
        out = {"hookEventName": "PreToolUse", "permissionDecision": "deny"}
        print(json.dumps({"hookSpecificOutput": {**out, "permissionDecisionReason": found}}))
    return 0


